#!/usr/bin/env python3
"""Regenerate the code appendix of docs/dashboard.md from the dashboard source files.

Everything above the marker line is hand-written and kept; everything below it is rewritten.
Run after changing dashboard.py, the template, charts.js or theme.css:  python scripts/build_dashboard_doc.py
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "dashboard.md"
MARKER = "<!-- CODE APPENDIX: generated by scripts/build_dashboard_doc.py; do not edit below -->"
FILES = [
    ("src/ogdata/analytics/dashboard.py", "python", "Builds the JSON payload (ticker, indicators, state production, heat-map cells, type curves, vintages, cash flow, tables, coverage) from the DuckDB views and writes the self-contained HTML."),
    ("src/ogdata/analytics/assets/dashboard_template.html", "html", "Page markup and all view-specific JavaScript (hash-routed tabs, map projection and layers, type-curve controls, tables). Placeholders /*__DATA__*/, /*__THEME_CSS__*/ and /*__CHARTS_JS__*/ are filled at build time."),
    ("src/ogdata/analytics/assets/charts.js", "javascript", "Shared D3 chart primitives: lineChart, fanChart, stackedArea, barChart (incl. tornado), table, tooltip and number formats."),
    ("src/ogdata/analytics/assets/theme.css", "css", "TCRED design tokens (dark panel palette, IBM Plex Mono, amber accent) and layout."),
    ("scripts/build_basins_asset.py", "python", "Builds assets/basins.json (basin and play outlines) from the public EIA, BC and AGS layers."),
]


def main() -> None:
    text = DOC.read_text()
    head = text.split(MARKER)[0].rstrip() + "\n\n" + MARKER + "\n\n"
    parts = ["## Appendix: dashboard source code\n\nGenerated from the repository; the map assets (`states-10m.json`, `na-provinces.json`, `basins.json`) are data files and are not reproduced.\n"]
    for rel, lang, blurb in FILES:
        src = (ROOT / rel).read_text()
        parts.append(f"\n### `{rel}`\n\n{blurb}\n\n```{lang}\n{src.rstrip()}\n```\n")
    DOC.write_text(head + "".join(parts))
    print(f"wrote {DOC} ({DOC.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
